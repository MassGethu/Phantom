"""Render a Copilot coding agent setup workflow from README steps that just passed."""

from pathlib import Path
import re

from ghostdev import config

WORKFLOW_PATH = Path(".github/workflows/copilot-setup-steps.yml")
INDENT = " " * 10


def python_version(image: str) -> str | None:
    match = re.match(r"(?:.*/)?python:(\d+\.\d+)", image)
    return match[1] if match else None


def render_workflow(commands: list[str], image: str = config.IMAGE) -> str:
    """One bash step, matching the single shell session the commands were verified in."""
    if not commands:
        raise ValueError("No verified commands to emit.")
    version = python_version(image)
    setup_python = (f'      - uses: actions/setup-python@v5\n        with:\n'
                    f'          python-version: "{version}"\n') if version else ""
    # A literal block keeps commands byte-for-byte; every line gets the same indent.
    body = "".join(f"{INDENT}{line}\n" if line.strip() else "\n"
                   for command in commands for line in command.splitlines())
    return (
        f"# Generated by ghostdev from README steps that passed in a fresh {image} container.\n"
        "# Review before committing: GitHub runners are not that container.\n"
        "name: Copilot Setup Steps\n"
        "on:\n"
        "  workflow_dispatch:\n"
        "  push:\n"
        f"    paths: [{WORKFLOW_PATH}]\n"
        "  pull_request:\n"
        f"    paths: [{WORKFLOW_PATH}]\n"
        "jobs:\n"
        "  copilot-setup-steps:\n"
        "    runs-on: ubuntu-latest\n"
        "    permissions:\n"
        "      contents: read\n"
        "    steps:\n"
        "      - uses: actions/checkout@v4\n"
        f"{setup_python}"
        "      - name: README setup (verified by ghostdev)\n"
        "        shell: bash\n"
        "        run: |\n"
        f"{body}"
    )
